#!/usr/bin/env python3
"""Writes docs/design/inputs/carried-text-report.md.

How much free text the shipped content carries unchanged from the source pack, from the importer's report
(docs/design/inputs/import-report/report.json, objects[].verbatim_text: one {field, length} per free-text field
the converter kept as written) and, for the two Section dashboards the report leaves out, from their YAML.
Run from the repository root:  python3 docs/design/tools/carried_text_report.py
"""
import json
import collections
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
REPORT = ROOT / "docs/design/inputs/import-report/report.json"
OUT = ROOT / "docs/design/inputs/carried-text-report.md"
SECTION_FILES = ["dashboards/overall-daily-check.yaml", "dashboards/vsphere-cluster-capacity-2-0.yaml"]


def kind_of(otype, field):
    if otype == "dashboard" and field.startswith("widget "):
        return "widget " + field.split(" ", 2)[2]
    return field


def walk(widgets, out, dash):
    for w in widgets or []:
        if not isinstance(w, dict):
            continue  # a Section lists the ids of its members
        wid = w.get("id")
        for key in ("title", "description", "html"):
            v = w.get(key)
            if isinstance(v, str) and v.strip():
                out.append((dash, f"widget w{wid} {key}", len(v)))
        walk(w.get("widgets"), out, dash)


def main():
    rep = json.loads(REPORT.read_text())
    rows = []  # (type, name, field, length)
    for o in rep["objects"]:
        for v in o["verbatim_text"]:
            rows.append((o["type"], o["name"], v["field"], v["length"]))
    sec = []
    for f in SECTION_FILES:
        y = yaml.safe_load((ROOT / f).read_text())
        items = []
        for key in ("name", "description"):
            if isinstance(y.get(key), str) and y[key].strip():
                items.append((y["name"], key, len(y[key])))
        walk(y.get("widgets"), items, y["name"])
        sec.extend(items)
    sec_rows = [("dashboard", n, fld, ln) for n, fld, ln in sec]

    def table(rs):
        agg = collections.OrderedDict()
        for t, _, fld, ln in rs:
            k = (t, kind_of(t, fld))
            c, ch = agg.get(k, (0, 0))
            agg[k] = (c + 1, ch + ln)
        return agg

    def by_type(rs):
        agg = collections.OrderedDict()
        for t, _, _, ln in rs:
            c, ch = agg.get(t, (0, 0))
            agg[t] = (c + 1, ch + ln)
        return agg

    replaced = sum(1 for o in rep["objects"] if o.get("description_replaced"))
    replaced_with_desc = sum(
        1 for o in rep["objects"]
        if o.get("description_replaced") and any(v["field"] == "description" for v in o["verbatim_text"]))
    renamed = sum(1 for line in (ROOT / "docs/design/inputs/view_rename.tsv").read_text().splitlines() if line.strip())
    allrows = rows + sec_rows
    L = []
    a = L.append
    a("# Carried text report")
    a("")
    a("Generated by `docs/design/tools/carried_text_report.py` from `docs/design/inputs/import-report/report.json`")
    a("(`objects[].verbatim_text`) and, for the two Section dashboards that file does not cover, from their YAML.")
    a("")
    a("What it counts: every free-text field (name, description, widget title, widget description, text widget HTML)")
    a("that the converter kept as the source pack wrote it. The importer records each as `{field, length}`; the length")
    a("is the field's length in characters (checked against the YAML for a super metric description, 374, and a text")
    a("widget, 504). It does not count identifiers, metric and property keys, formulas, symptom conditions or any")
    a("other structured value. A field the converter replaced is not counted. Whether the carried text is protected")
    a("expression, or is a title or a name too short to be one, is the owner's decision; this report only shows where")
    a("it is.")
    a("")
    a("## Replaced text")
    a("")
    a(f"- {replaced} views have a replaced description: the 101 re-authored views (the ones that began as edited built-in")
    a("  views), each described afresh from its subject, columns, filters and time settings")
    a("  (`docs/design/inputs/view_describe.tsv`). Of these, " + str(replaced_with_desc) + " still carry a source description.")
    a(f"- {renamed} of those views also have a new title (`docs/design/inputs/view_rename.tsv`): the titles that equalled a")
    a(f"  built-in view's. The other {replaced - renamed} keep the source title, which is counted below as carried.")
    a("- The 19 views that only renamed a built-in are not shipped (the dashboards and reports use the built-in in place).")
    a("")
    a("## Totals")
    a("")
    a("| What | Fields | Characters |")
    a("|---|---:|---:|")
    a(f"| Importer report, {len(rep['objects'])} objects | {len(rows)} | {sum(r[3] for r in rows)} |")
    a(f"| The two Section dashboards (from their YAML) | {len(sec_rows)} | {sum(r[3] for r in sec_rows)} |")
    a(f"| **All carried free text** | **{len(allrows)}** | **{sum(r[3] for r in allrows)}** |")
    a("")
    a("## By type")
    a("")
    a("| Type | Fields | Characters |")
    a("|---|---:|---:|")
    for t, (c, ch) in sorted(by_type(allrows).items()):
        a(f"| {t} | {c} | {ch} |")
    a("")
    a("## By type and field")
    a("")
    a("Widget fields are grouped by what they are, not by widget number. The Section dashboards are included.")
    a("")
    a("| Type | Field | Fields | Characters |")
    a("|---|---|---:|---:|")
    for (t, f), (c, ch) in sorted(table(allrows).items()):
        a(f"| {t} | {f} | {c} | {ch} |")
    a("")
    a("## The ten largest fields")
    a("")
    a("| # | Type | Object | Field | Characters |")
    a("|---:|---|---|---|---:|")
    for i, (t, n, f, ln) in enumerate(sorted(allrows, key=lambda r: (-r[3], r[0], r[1], r[2]))[:10], 1):
        a(f"| {i} | {t} | {n} | {f} | {ln} |")
    a("")
    a("## Not covered here")
    a("")
    a("- Text inside structured values: symptom and alert conditions and messages in fields other than `name` and")
    a("  `description`, super metric formulas, view column labels, report section text. The importer's `verbatim_text`")
    a("  does not list them; column labels and formulas are keys and expressions of the data, not prose.")
    a("- The two Section dashboards are read from the shipped YAML, not from the report, so their figures count every")
    a("  non-empty name, description, title, widget description and text widget HTML in the file.")
    a("")
    OUT.write_text("\n".join(L))
    print(OUT, len(allrows), sum(r[3] for r in allrows))


main()
